-- =============================================================================
-- PASSWORD_RESET_TOKENS TABLE
-- =============================================================================

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    hash       CHAR(64) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uq_password_reset_tokens_hash UNIQUE (hash),
    CONSTRAINT fk_password_reset_tokens_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

COMMENT ON COLUMN password_reset_tokens.hash IS 'SHA-256 hex of the emailed token; the raw token is never stored';
COMMENT ON COLUMN password_reset_tokens.used_at IS 'Set when the token is used or superseded by a newer request';

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_unused ON password_reset_tokens (user_id) WHERE used_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_expires_at ON password_reset_tokens (expires_at);
